ANCHO, ALTO, AVANCE = 5, 7, 6          # ancho de letra, alto y cuánto avanza (con 1 px de espacio)
_cache = {}


def text_width(text, scale=1):
    return max(0, len(text) * AVANCE - 1) * scale


def pixel_text(text, color=(255, 255, 255), scale=1, outline=None):
    """Devuelve una Surface con el texto. outline=(r,g,b) agrega un contorno de 1 píxel de fuente."""
    key = (text, color, scale, outline)
    if key in _cache:
        return _cache[key]
    text = text.upper()
    pad = 1 if outline else 0
    w = (len(text) * AVANCE - 1 + 2 * pad) * scale
    h = (ALTO + 2 * pad) * scale
    surf = pygame.Surface((max(1, w), h), pygame.SRCALPHA)

    def paint(col, dx, dy):
        for i, ch in enumerate(text):
            rows = _G.get(ch, _G["?"])
            for ry, row in enumerate(rows):
                for rx, c in enumerate(row):
                    if c == "#":
                        x = (pad + i * AVANCE + rx + dx) * scale
                        y = (pad + ry + dy) * scale
                        surf.fill(col, (x, y, scale, scale))

    if outline:
        for dx in (-1, 0, 1):
            for dy in (-1, 0, 1):
                if dx or dy:
                    paint(outline, dx, dy)
    paint(color, 0, 0)
    _cache[key] = surf
    return surf


def draw_pixel_text(surface, text, color, scale=1, center=None, topleft=None, midleft=None, outline=None):
    img = pixel_text(text, color, scale, outline)
    r = img.get_rect()
    if center:
        r.center = center
    elif midleft:
        r.midleft = midleft
    elif topleft:
        r.topleft = topleft
    surface.blit(img, r)
    return r
